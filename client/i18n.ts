export function isChineseLocale(locale?: string | null): boolean {
  if (!locale) return false;
  return locale.toLowerCase().startsWith("zh");
}

export function getCatalogForLocale(locale?: string | null): PluginMessageCatalog {
  return isChineseLocale(locale) ? zhMessages : enMessages;
}
